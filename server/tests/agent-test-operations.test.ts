import { test, after } from 'node:test';
import assert from 'node:assert/strict';
import { mkdtempSync, rmSync } from 'node:fs';
import { tmpdir } from 'node:os';
import path from 'node:path';
const dir=mkdtempSync(path.join(tmpdir(),'lkc-test-privacy-'));
Object.assign(process.env,{DB_PATH:path.join(dir,'project.db'),LIVEKIT_URL:'ws://127.0.0.1:1',LIVEKIT_API_KEY:'test',LIVEKIT_API_SECRET:'test',ADMIN_USER:'admin',ADMIN_PASSWORD:'test-password',SESSION_SECRET:'test-secret'});
await import('../src/operations.js');
const store=await import('../src/agent-test-store.js');
const {registerOperationsStore}=await import('../src/operations-stores.js');
const {updatePolicy,exportCategory,deleteCategory,storageMeasurements,maintainOperations}=await import('../src/operations-policy.js');
const {db}=await import('../src/db.js');
registerOperationsStore('agent-tests',{category:'live',maintain:store.maintainAgentTestContent,scrub:store.scrubAgentTestContent,delete:store.deleteAgentTestContent,storage:store.agentTestStorage,export:store.exportAgentTestContent});
after(()=>{db.close();rmSync(dir,{recursive:true,force:true});});
test('test scenarios/results inherit Operations redaction, expiry, counts, export and deletion',()=>{
 const scenario=store.saveScenario({name:'Fixture',prompts:[{text:'private prompt',expectedSubstring:'private response',timeoutSeconds:10}]});
 const row=store.createRun('fixture-agent',scenario,null);store.activateRun(row.id,'RM_fixture');
 const sent=Date.now();store.saveResults(row.id,{results:[{promptIndex:0,status:'received',responseText:'private response',sentAt:sent,receivedAt:sent,source:'lk.transcription'}]});
 updatePolicy({redaction:'standard',redactTerms:['private prompt','private response']});
 const output=JSON.stringify(exportCategory('live',true));assert.ok(!output.includes('private prompt'));assert.ok(!output.includes('private response'));assert.ok(output.includes('[REDACTED]'));
 assert.equal(storageMeasurements().categories.live.tables.agent_test_runs,1);
 assert.ok(!JSON.stringify(exportCategory('live',false)).includes('Fixture'));
 assert.throws(()=>exportCategory('live',true,128));
 const deletion=deleteCategory('live');assert.equal(deletion.tables.agent_test_scenarios,1);assert.equal(db.prepare('SELECT content FROM agent_test_runs WHERE id=?').get(row.id)!.content,null);
 assert.throws(()=>store.saveResults(row.id,{results:[{promptIndex:0,status:'received',responseText:'resurrection',sentAt:sent,receivedAt:sent,source:'lk.transcription'}]}));
 assert.throws(()=>store.scenarioById(scenario.id));
 const later=store.saveScenario({name:'Expiring',prompts:[{text:'retained for now',timeoutSeconds:10}]});
 db.prepare('UPDATE agent_test_scenarios SET created_at=? WHERE id=?').run(Date.now()-2*86400000,later.id);
 updatePolicy({categories:{live:{retentionDays:1}}});maintainOperations();assert.throws(()=>store.scenarioById(later.id));
 updatePolicy({categories:{live:{retentionDays:30}}});assert.equal(db.prepare('SELECT content FROM agent_test_scenarios WHERE id=?').get(later.id)!.content,null);
});
