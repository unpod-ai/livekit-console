import { after, test } from 'node:test';
import assert from 'node:assert/strict';
import { mkdtempSync, rmSync } from 'node:fs';
import { tmpdir } from 'node:os';
import path from 'node:path';
const dir = mkdtempSync(path.join(tmpdir(), 'inventory-'));
Object.assign(process.env, { DB_PATH: path.join(dir, 'test.db'), LIVEKIT_URL: 'ws://localhost', LIVEKIT_API_KEY: 'test', LIVEKIT_API_SECRET: 'test', ADMIN_USER: 'admin', ADMIN_PASSWORD: 'test', SESSION_SECRET: 'test' });
const store = await import('../src/inventory-store.js');
const { db } = await import('../src/db.js');
const { config } = await import('../src/config.js');
after(() => { db.close(); rmSync(dir, { recursive: true, force: true }); });
test('explicit aliases require exact merge confirmation, preserve redirects and source names', () => {
 const a = store.ensureAgentName('old', 100), b = store.ensureAgentName('new', 200);
 assert.notEqual(a.id, b.id);
 assert.throws(() => store.linkAgentAlias(a.id, { name: 'new' }));
 assert.throws(() => store.linkAgentAlias(a.id, { name: 'new', mergeAgentId: a.id }));
 store.linkAgentAlias(a.id, { name: 'new', mergeAgentId: b.id, makeCanonical: true });
 assert.equal(store.resolveAgent(b.id)?.id, a.id);
 assert.equal(store.resolveAgent('old')?.name, 'new');
 assert.deepEqual(store.agentAliases(a.id).sort(), ['new', 'old']);
 assert.deepEqual(store.agentAliases('unseen'), ['unseen']);
});
test('durable workers split native IDs, survive removal and raw deletion, rollups migrate only once', () => {
 config.workerUrls = ['http://worker'];
 const at = Date.now() - 3600000;
 const observation = { url: 'http://worker', agentName: 'old', workerId: 'AW_one', ok: true, checkedAt: at, load: null, infoAvailable: true };
 store.recordWorkerObservation(observation);
 const first = store.inventoryWorkerRows(24, 'new').workers[0];
 assert.match(first.consoleWorkerId, /^CW_/); assert.equal(first.workerId, 'AW_one');
 store.recordWorkerObservation({ ...observation, workerId: 'AW_two', checkedAt: at + 1000 });
 let rows = store.inventoryWorkerRows(24, 'new');
 assert.equal(rows.former.length, 1); assert.notEqual(rows.workers[0].consoleWorkerId, first.consoleWorkerId);
 store.syncInventory(); store.syncInventory();
 assert.equal(store.workerRollups('new', 365).series.reduce((n, r) => n + r.samples, 0), 2);
 assert.equal(store.workerRollups('new', 365).series[0].avgLoadPct, null);
 db.exec('DELETE FROM agent_worker_samples'); config.workerUrls = []; store.syncInventory();
 rows = store.inventoryWorkerRows(24, 'old');
 assert.equal(rows.workers.length, 0); assert.equal(rows.former.length, 2);
 assert.equal(store.workerRollups('old', 365).series.reduce((n, r) => n + r.samples, 0), 2);
});
test('a new configured instance does not inherit the previous worker successful observations', () => {
 const url = 'http://replacement-worker';
 config.workerUrls = [url];
 config.workerMetadata[url] = { instanceKey: 'first' };
 const at = Date.now() - 1000;
 store.recordWorkerObservation({ url, agentName: 'replacement-agent', checkedAt: at, ok: true, infoAvailable: true });
 config.workerMetadata[url] = { instanceKey: 'second' };
 store.recordWorkerObservation({ url, agentName: 'replacement-agent', checkedAt: at + 1000, ok: false, infoAvailable: false });
 const rows = store.inventoryWorkerRows(24, 'replacement-agent');
 assert.equal(rows.former.length, 1);
 assert.equal(rows.workers[0].lastSeenAt, null);
 assert.equal(rows.workers[0].lastInfoAt, null);
 assert.equal(rows.workers[0].lastOkAt, null);
 assert.equal(rows.former[0].lastSeenAt, at);
});
test('source names resembling console IDs remain distinct and do not break backfill', () => {
 const first = store.ensureAgentName('CA_sales');
 const literal = store.ensureAgentName(first.id);
 assert.notEqual(literal.id, first.id);
 assert.equal(store.resolveAgent(first.id)?.name, 'CA_sales');
 assert.equal(store.resolveAgent(literal.id)?.name, first.id);
 db.prepare('INSERT INTO participants(room_sid,sid,identity,kind,joined_at,attributes) VALUES(?,?,?,?,?,?)').run('RM_prefix', 'PA_prefix', 'agent', '4', Date.now(), JSON.stringify({ 'lk.agent.name': 'CW_sales' }));
 assert.doesNotThrow(() => store.syncInventory());
 assert.ok(store.resolveAgent('CW_sales'));
});
test('hour-aligned windows retain checks from the first partial requested hour', t => {
 const now = Math.floor(Date.now() / 3600000) * 3600000 + 30 * 60000;
 t.mock.method(Date, 'now', () => now);
 const url = 'http://boundary-worker'; config.workerUrls = [url];
 store.recordWorkerObservation({ url, agentName: 'boundary-agent', checkedAt: now - 86400000 + 60000, ok: false });
 store.recordWorkerObservation({ url, agentName: 'boundary-agent', checkedAt: now, ok: true });
 const r = store.workerRollups('boundary-agent', 1);
 assert.equal(r.series.reduce((n, p) => n + p.samples, 0), 2);
 assert.equal(r.from, Math.floor((now - 86400000) / 3600000) * 3600000);
 assert.equal(store.inventoryWorkerRows(24, 'boundary-agent').workers[0].uptimePct, 50);
});
